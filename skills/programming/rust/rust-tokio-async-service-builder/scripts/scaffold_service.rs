fn die(msg: &str) -> ! {
    eprintln!("error: {msg}");
    exit(2);
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.iter().any(|a| a == "-h" || a == "--help") {
        println!("{USAGE}");
        return;
    }
    let (mut name, mut file, mut out, mut force) = ("my-service".to_string(), None, None, false);
    let mut it = args.iter();
    while let Some(a) = it.next() {
        let mut val = || it.next().cloned().unwrap_or_else(|| die(&format!("{a} needs a value")));
        match a.as_str() {
            "--name" => name = val(),
            "--file" => file = Some(val()),
            "--out" => out = Some(val()),
            "--force" => force = true,
            other => die(&format!("unknown argument {other}\n\n{USAGE}")),
        }
    }
    let valid = name.chars().next().is_some_and(|c| c.is_ascii_lowercase())
        && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_');
    if !valid {
        die(&format!("--name must be lowercase letters, digits, '-' or '_', got '{name}'"));
    }
    let cargo = CARGO.replace("{name}", &name);
    let main = MAIN.replace("{name}", &name);
    match (out, file.as_deref()) {
        (Some(dir), _) => {
            let targets = [(Path::new(&dir).join("Cargo.toml"), cargo), (Path::new(&dir).join("src/main.rs"), main)];
            if !force {
                if let Some((p, _)) = targets.iter().find(|(p, _)| p.exists()) {
                    die(&format!("{} exists; pass --force to overwrite", p.display()));
                }
            }
            for (p, text) in &targets {
                if let Some(parent) = p.parent() {
                    std::fs::create_dir_all(parent).unwrap_or_else(|e| die(&format!("cannot create {}: {e}", parent.display())));
                }
                std::fs::write(p, text).unwrap_or_else(|e| die(&format!("cannot write {}: {e}", p.display())));
                println!("wrote {}", p.display());
            }
        }
        (None, Some("main")) => print!("{main}"),
        (None, Some("cargo")) => print!("{cargo}"),
        (None, Some(other)) => die(&format!("--file must be main or cargo, got '{other}'")),
        (None, None) => print!("# Cargo.toml\n{cargo}\n// src/main.rs\n{main}"),
    }
}
