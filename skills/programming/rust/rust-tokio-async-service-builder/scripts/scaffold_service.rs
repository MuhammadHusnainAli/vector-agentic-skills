//! Generate a minimal production-shaped axum 0.8 service: Cargo.toml + src/main.rs with shared
//! state, an AppError that maps to HTTP, health/readiness, tracing, timeout and body-limit
//! layers, a TaskTracker + CancellationToken background task, graceful shutdown and tests.
//! The output compiles, its tests pass, and it passes this skill's scanners.
//!
//! Build: rustc -O --edition 2021 scripts/scaffold_service.rs -o /tmp/scaffold_service
//! Usage: scaffold_service [--name NAME] [--file main|cargo] [--out DIR [--force]]

use std::path::Path;
use std::process::exit;

const USAGE: &str = "usage: scaffold_service [--name NAME] [--file main|cargo] [--out DIR [--force]]

Print (or write) a minimal axum 0.8 / tokio 1 service:
  Cargo.toml    axum 0.8, tokio 1, tower 0.5, tower-http 0.6, tokio-util 0.7, tracing, thiserror 2
  src/main.rs   AppState, AppError -> IntoResponse, /healthz, /readyz, /items/{id}, TraceLayer,
                TimeoutLayer, RequestBodyLimitLayer, a TaskTracker background task stopped by a
                CancellationToken, graceful shutdown on Ctrl+C/SIGTERM, oneshot router tests

options:
  --name NAME   crate name (lowercase, digits, '-' or '_'; default: my-service)
  --file F      print only `main` (src/main.rs) or `cargo` (Cargo.toml)
  --out DIR     write DIR/Cargo.toml and DIR/src/main.rs instead of printing
  --force       overwrite existing files with --out
Exit: 0 done, 2 usage error or files exist without --force.";

