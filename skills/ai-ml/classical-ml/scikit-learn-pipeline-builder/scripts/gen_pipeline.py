#!/usr/bin/env python3
"""Generate a production-shaped scikit-learn training script for a CSV: Pipeline + ColumnTransformer,
the right CV splitter, optional hyperparameter search, evaluation, persistence and a predict() helper.

Column roles are inferred from a sample (numeric, low-/high-cardinality categorical, datetime, text, ID,
constant) and can be overridden. Generated pipeline per model family:
  linear   numeric: median impute (+indicator) -> StandardScaler; categorical: OneHot(min_frequency);
           high-card: TargetEncoder; text: TF-IDF; dates: DateFeatures transformer -> scaled
  hgb      HistGradientBoosting with native categoricals (OrdinalEncoder, categorical_features mask),
           no scaling; high-card: TargetEncoder
  rf       RandomForest: ordinal-encoded categoricals, median imputation
CV: stratified K-fold (classification), K-fold (regression), GroupKFold (--group-col) or
TimeSeriesSplit on rows sorted by --time-col (with --gap). Search: none | random | halving.

The generated script needs pandas, scikit-learn >= 1.4 and joblib. This generator is stdlib only.

Usage:
    python gen_pipeline.py data.csv --target churned --model hgb --time-col signup_date -o train.py
    python gen_pipeline.py data.csv --target price --model linear --search random --drop house_id
    python gen_pipeline.py data.csv --target churned --group-col customer_id --text-cols notes

Exit codes: 0 written, 2 usage or read error.
"""

import argparse
import csv
import math
import os
import re
import sys
from itertools import islice

MISSING = {"", "na", "n/a", "nan", "null", "none", "?"}
DATE_RE = re.compile(r"^\d{4}[-/]\d{1,2}[-/]\d{1,2}")


def is_num(v):
    try:
        return math.isfinite(float(v))
    except ValueError:
        return False


def roles(header, rows, target, drop, time_col, group_col, text_cols, cat_cols):
    out = {"numeric": [], "categorical": [], "high_card": [], "date": [], "text": list(text_cols), "dropped": []}
    for c in header:
        if c in (target, group_col) or c in drop or c in text_cols:
            continue
        vals = [(r.get(c) or "").strip() for r in rows]
        present = [v for v in vals if v.lower() not in MISSING]
        if not present or len(set(present)) == 1:
            out["dropped"].append((c, "empty or constant"))
            continue
        k = len(set(present))
        if c in cat_cols:
            out["high_card" if k > 50 else "categorical"].append(c)
        elif c == time_col or sum(bool(DATE_RE.match(v)) for v in present) / len(present) > 0.9:
            out["date"].append(c)
        elif all(is_num(v) for v in present):
            if re.search(r"(^id$|_id$)", c, re.I) and k > 0.9 * len(present):
                out["dropped"].append((c, "numeric ID"))
            elif re.search(r"(zip|postcode|_code$)", c, re.I):
                out["high_card" if k > 50 else "categorical"].append(c)
            else:
                out["numeric"].append(c)
        elif k > 0.9 * len(present):
            mean_len = sum(len(v) for v in present) / len(present)
            if mean_len > 30:
                out["text"].append(c)
            else:
                out["dropped"].append((c, "near-unique text (ID)"))
        elif k > 50:
            out["high_card"].append(c)
        else:
            out["categorical"].append(c)
    return out


