def main():
    ap = argparse.ArgumentParser(description="Generate a scikit-learn Pipeline training script for a CSV.",
                                 epilog=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv")
    ap.add_argument("--target", required=True)
    ap.add_argument("--task", choices=["auto", "classification", "regression"], default="auto")
    ap.add_argument("--model", choices=["linear", "hgb", "rf"], default="hgb")
    ap.add_argument("--time-col")
    ap.add_argument("--gap", type=int, default=0, help="TimeSeriesSplit gap (rows) between train and test folds")
    ap.add_argument("--group-col")
    ap.add_argument("--folds", type=int, default=5)
    ap.add_argument("--search", choices=["none", "random", "halving"], default="none")
    ap.add_argument("--drop", nargs="*", default=[])
    ap.add_argument("--text-cols", nargs="*", default=[])
    ap.add_argument("--cat-cols", nargs="*", default=[], help="force these columns to be categorical")
    ap.add_argument("-o", "--output")
    a = ap.parse_args()
    try:
        with open(a.csv, newline="", encoding="utf-8-sig") as fh:
            reader = csv.DictReader(fh)
            header = reader.fieldnames or []
            rows = list(islice(reader, 5000))
    except OSError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    for c in [a.target, a.time_col, a.group_col, *a.text_cols, *a.cat_cols]:
        if c and c not in header:
            print(f"error: column {c!r} not found", file=sys.stderr)
            return 2
    tv = {(r.get(a.target) or "").strip() for r in rows} - {""}
    task = a.task if a.task != "auto" else ("classification" if len(tv) <= 20 or not all(is_num(v) for v in tv)
                                            else "regression")
    rl = roles(header, rows, a.target, set(a.drop), a.time_col, a.group_col, set(a.text_cols), set(a.cat_cols))
    if a.time_col and a.time_col in rl["date"]:
        rl["date"].remove(a.time_col)        # ordering only; raw calendar position of the split column is not a feature
        rl["dropped"].append((a.time_col, "time column used for ordering"))
    if a.group_col:
        rl["dropped"].append((a.group_col, "group key for CV"))
    model, model_import, dist = MODELS[(a.model, task)]
    # leaf-size ranges must fit the smallest training fold (TimeSeriesSplit's first fold is ~1/(k+1) of the rows)
    leaf_hi = max(10, min(200, len(rows) // (4 * (a.folds + 1))))
    dist = dist.replace("randint(10, 200)", f"randint(5, {leaf_hi})").replace("randint(1, 50)", f"randint(1, {max(5, leaf_hi // 2)})")
    extra = [model_import]
    if rl["text"]:
        extra.append("from sklearn.feature_extraction.text import TfidfVectorizer")
        if a.model != "linear":
            extra.append("from sklearn.decomposition import TruncatedSVD")
    if a.search != "none":
        extra.append("from scipy.stats import loguniform, randint, uniform")
    if a.search == "halving":
        extra.append("from sklearn.experimental import enable_halving_search_cv  # noqa: F401  (must precede the import)")
        extra.append("from sklearn.model_selection import HalvingRandomSearchCV")
    binary = task == "classification" and len(tv) == 2
    if task == "classification":
        scoring = '["roc_auc", "average_precision", "neg_log_loss"]' if binary else '["accuracy", "f1_macro", "neg_log_loss"]'
        primary = "average_precision" if binary else "f1_macro"
    else:
        scoring = '["neg_mean_absolute_error", "neg_root_mean_squared_error", "r2"]'
        primary = "neg_mean_absolute_error"
    if a.time_col:
        splitter, cv_expr = "TimeSeriesSplit", f"TimeSeriesSplit(n_splits={a.folds}, gap={a.gap})   # rows sorted by time in load()"
        load_extra = f"    df = df.sort_values({a.time_col!r}).reset_index(drop=True)\n"
    elif a.group_col:
        splitter = "StratifiedGroupKFold" if task == "classification" else "GroupKFold"
        cv_expr = (f"StratifiedGroupKFold(n_splits={a.folds}, shuffle=True, random_state=SEED)" if task == "classification"
                   else f"GroupKFold(n_splits={a.folds})")
        load_extra = ""
    else:
        splitter = "StratifiedKFold" if task == "classification" else "KFold"
        cv_expr = f"{splitter}(n_splits={a.folds}, shuffle=True, random_state=SEED)"
        load_extra = ""
    groups_kw = ", groups=groups" if a.group_col else ""
    if task == "classification" and binary:
        target_prep = ("    positive = df[TARGET].value_counts().idxmin()        # minority class = positive\n"
                       "    y = (df[TARGET] == positive).astype(int)\n")
        classes_entry, predict_expr = ', "positive": positive', 'bundle["model"].predict_proba(X)[:, 1]'
    elif task == "classification":
        target_prep = "    y = df[TARGET].astype(str)\n"
        classes_entry, predict_expr = "", 'bundle["model"].predict_proba(X)'
    else:
        target_prep = "    y = df[TARGET].astype(float)\n"
        classes_entry, predict_expr = "", 'bundle["model"].predict(X)'
    if a.group_col:
        target_prep += f"    groups = df.pop({a.group_col!r})\n"
    target_prep += f"    df = df.drop(columns=[c for c, _ in DROP if c in df.columns and c != TARGET])\n"
    search_block = ""
    if a.search != "none":
        cls = "RandomizedSearchCV" if a.search == "random" else "HalvingRandomSearchCV"
        n_iter = "n_iter=40, " if a.search == "random" else "factor=3, "
        search_block = (f"    search = {cls}(model, {dist}, {n_iter}scoring={primary!r}, cv=cv, random_state=SEED, n_jobs=-1)\n"
                        f"    search.fit(X, y{groups_kw})\n"
                        "    print(\"best params:\", search.best_params_, \"inner score:\", round(search.best_score_, 4))\n"
                        "    model = search.best_estimator_\n"
                        "    # cross_validate below re-scores the tuned configuration on the same folds (optimistic);\n"
                        "    # for an unbiased estimate wrap the search itself in cross_validate (nested CV).\n")
    cat_mask = ""
    if a.model == "hgb":
        cat_mask = ("\n# HistGradientBoosting: the ordinal-encoded CATEGORICAL block is first in the ColumnTransformer, so\n"
                    "# its output columns are 0..len(CATEGORICAL)-1 whatever the width of the later blocks\n"
                    "CAT_MASK = list(range(len(CATEGORICAL))) or None\n")
    num_step = '"passthrough"' if a.model == "hgb" else 'SimpleImputer(strategy="median")'
    script_name = os.path.basename(a.output or "train.py")
    search_import = ""
    if a.search == "random":
        search_import = ", RandomizedSearchCV"
    text = HEADER.format(task=task, target=a.target, script=script_name, data=a.csv, splitter=splitter,
                         search_import=search_import, extra_imports="\n".join(extra) + "\n",
                         numeric=rl["numeric"], categorical=rl["categorical"], high_card=rl["high_card"],
                         date=rl["date"], text=rl["text"], dropped=rl["dropped"],
                         group_line=f"GROUP = {a.group_col!r}\n" if a.group_col else "",
                         time_line=f"TIME = {a.time_col!r}\n" if a.time_col else "")
    text += f"SCORING = {scoring}\n" + cat_mask
    if rl["text"] and a.model != "linear":
        text += TEXT_SVD
    text += (PREP_LINEAR if a.model == "linear" else PREP_TREE.format(num_step=num_step))
    text += BODY.format(model=model, data=a.csv, load_extra=load_extra, target_prep=target_prep, cv_expr=cv_expr,
                        search_block=search_block, groups_kw=groups_kw, classes_entry=classes_entry,
                        predict_expr=predict_expr)
    if a.output:
        with open(a.output, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {a.output}: task={task}, model={a.model}, cv={splitter}, numeric={len(rl['numeric'])}, "
              f"categorical={len(rl['categorical'])}, high_card={len(rl['high_card'])}, dates={len(rl['date'])}, "
              f"text={len(rl['text'])}, dropped={len(rl['dropped'])}", file=sys.stderr)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
