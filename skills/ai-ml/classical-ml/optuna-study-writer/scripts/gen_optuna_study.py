"""Generate a complete, resumable Optuna study script for a CSV dataset.

The script it writes:
  - loads the data, builds fixed CV folds ONCE (stratified / grouped / time-ordered) so every trial is
    scored on the same splits
  - defines an objective for the chosen model (lgbm | xgb | catboost | hgb | rf | logreg) with a
    search space sized to the data, early stopping inside each fold for boosting models, and
    trial.report(...) after every fold so the pruner can stop bad trials
  - creates the study with a seeded TPESampler (multivariate), a MedianPruner or HyperbandPruner,
    and an SQLite storage + study_name + load_if_exists=True so interrupted runs resume
  - stops early when the best value has not improved for --patience trials (callback)
  - saves trials to CSV, prints parameter importances, refits the best configuration on all data
    (boosting: lower learning rate, scaled iterations) and saves it with joblib
The generated script needs optuna >= 3, pandas, scikit-learn and the chosen library.

Usage:
    python gen_optuna_study.py data.csv --target churned --model lgbm --metric average_precision -o study.py
    python gen_optuna_study.py data.csv --target price --model xgb --metric neg_root_mean_squared_error --trials 100
    python gen_optuna_study.py data.csv --target churned --model catboost --group-col customer_id --pruner hyperband

Exit codes: 0 written, 2 usage or read error.
"""

