def main():
    ap = argparse.ArgumentParser(description="Generate a resumable Optuna study script.", epilog=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv")
    ap.add_argument("--target", required=True)
    ap.add_argument("--model", choices=sorted(SPACE), default="lgbm")
    ap.add_argument("--metric", choices=sorted(METRICS), default="roc_auc")
    ap.add_argument("--drop", nargs="*", default=[])
    ap.add_argument("--group-col")
    ap.add_argument("--time-col")
    ap.add_argument("--folds", type=int, default=5)
    ap.add_argument("--trials", type=int, default=100)
    ap.add_argument("--patience", type=int, default=30)
    ap.add_argument("--pruner", choices=["median", "hyperband", "none"], default="median")
    ap.add_argument("--study-name")
    ap.add_argument("-o", "--output")
    a = ap.parse_args()
    try:
        with open(a.csv, newline="", encoding="utf-8-sig") as fh:
            rd = csv.DictReader(fh)
            header = rd.fieldnames or []
            rows = list(islice(rd, 20000))
    except OSError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    for c in (a.target, a.group_col, a.time_col):
        if c and c not in header:
            print(f"error: column {c!r} not found", file=sys.stderr)
            return 2
    metric_fn, kind, direction = METRICS[a.metric]
    classification = kind in ("proba", "label")
    n = len(rows)
    mcs = max(5, min(200, n // 100))
    leaves_hi = 255 if n > 100_000 else (127 if n > 20_000 else 63)
    drop = list(a.drop) + [c for c in (a.group_col, a.time_col) if c and c not in a.drop]
    if a.time_col:
        splitter, cv_expr = "TimeSeriesSplit", f"TimeSeriesSplit(n_splits={a.folds}).split(df)"
        order_line = f"df = df.sort_values({a.time_col!r}).reset_index(drop=True)\n"
    elif a.group_col:
        splitter = "StratifiedGroupKFold" if classification else "GroupKFold"
        cv_expr = (f"StratifiedGroupKFold(n_splits={a.folds}, shuffle=True, random_state=SEED).split(df, y, groups)"
                   if classification else f"GroupKFold(n_splits={a.folds}).split(df, y, groups)")
        order_line = ""
    else:
        splitter = "StratifiedKFold" if classification else "KFold"
        cv_expr = f"{splitter}(n_splits={a.folds}, shuffle=True, random_state=SEED).split(df, y)"
        order_line = ""
    groups_line = f"groups = df[{a.group_col!r}].to_numpy()\n" if a.group_col and not a.time_col else ""
    if classification:
        target_prep = ("positive = df[TARGET].value_counts().idxmin()\n"
                       "y = (df[TARGET] == positive).astype(int)\n")
    else:
        target_prep = "y = df[TARGET].astype(float)\n"
    if kind == "proba":
        clip = "np.clip(p, 1e-15, 1 - 1e-15)" if metric_fn == "log_loss" else "p"
        score_body = f"    p = model.predict_proba(X_te)[:, 1]\n    return {metric_fn}(y_true, {clip})"
    elif kind == "label":
        score_body = f"    return {metric_fn}(y_true, model.predict(X_te))"
    else:
        score_body = f"    return {metric_fn}(y_true, model.predict(X_te))"
    cls = {"lgbm": ("LGBMClassifier", "LGBMRegressor"), "xgb": ("XGBClassifier", "XGBRegressor"),
           "catboost": ("CatBoostClassifier", "CatBoostRegressor"),
           "hgb": ("HistGradientBoostingClassifier", "HistGradientBoostingRegressor"),
           "rf": ("RandomForestClassifier", "RandomForestRegressor"), "logreg": ("LogisticRegression", "Ridge")}[a.model]
    C = cls[0] if classification else cls[1]
    conditional = ""
    cat_prep = ""
    extra_req = {"lgbm": ", lightgbm", "xgb": ", xgboost", "catboost": ", catboost"}.get(a.model, "")
    if a.model == "lgbm":
        model_import = f"import lightgbm as lgb\nfrom lightgbm import {C}\n"
        cat_prep = "for c in CAT:\n    X[c] = X[c].astype(\"category\")\n"
        fit_block = (f"        model = {C}(**params, learning_rate=0.05, n_estimators=5000, random_state=SEED, verbose=-1)\n"
                     "        model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], callbacks=[lgb.early_stopping(100, verbose=False)])\n"
                     "        iters.append(model.best_iteration_)")
        refit = (f"    best = dict(study.best_params, subsample_freq=1)\n"
                 "    n_trees = int(study.best_trial.user_attrs.get('best_iteration_mean', 500) * 2 * 1.1)\n"
                 f"    final = {C}(**best, learning_rate=0.025, n_estimators=n_trees, random_state=SEED, verbose=-1).fit(X, y)")
    elif a.model == "xgb":
        model_import = f"from xgboost import {C}\n"
        cat_prep = "for c in CAT:\n    X[c] = X[c].astype(\"category\")\n"
        fit_block = (f"        model = {C}(**params, learning_rate=0.05, n_estimators=5000, tree_method=\"hist\",\n"
                     "                    enable_categorical=True, early_stopping_rounds=100, random_state=SEED)\n"
                     "        model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], verbose=False)\n"
                     "        iters.append(model.best_iteration)")
        refit = ("    n_trees = int(study.best_trial.user_attrs.get('best_iteration_mean', 500) * 2 * 1.1)\n"
                 f"    final = {C}(**study.best_params, learning_rate=0.025, n_estimators=n_trees, tree_method=\"hist\",\n"
                 "                 enable_categorical=True, random_state=SEED).fit(X, y)")
    elif a.model == "catboost":
        model_import = f"from catboost import {C}\n"
        cat_prep = "for c in CAT:\n    X[c] = X[c].astype(\"string\").fillna(\"__nan__\").astype(str)\n"
        conditional = ('    if params["bootstrap_type"] == "Bayesian":\n'
                       '        params["bagging_temperature"] = trial.suggest_float("bagging_temperature", 0.0, 1.0)\n'
                       '    else:\n'
                       '        params["subsample"] = trial.suggest_float("subsample", 0.6, 1.0)\n')
        fit_block = (f"        model = {C}(**params, learning_rate=0.05, iterations=3000, od_type=\"Iter\", od_wait=100,\n"
                     "                    cat_features=CAT, random_seed=SEED, verbose=0, allow_writing_files=False)\n"
                     "        model.fit(X_tr, y_tr, eval_set=(X_te, y_te), use_best_model=True)\n"
                     "        iters.append(model.get_best_iteration())")
        refit = ("    n_trees = int(study.best_trial.user_attrs.get('best_iteration_mean', 500) * 2 * 1.1)\n"
                 f"    final = {C}(**study.best_params, learning_rate=0.025, iterations=n_trees, cat_features=CAT,\n"
                 "                 random_seed=SEED, verbose=0, allow_writing_files=False).fit(X, y)")
    else:
        sk_mod = {"hgb": "sklearn.ensemble", "rf": "sklearn.ensemble", "logreg": "sklearn.linear_model"}[a.model]
        model_import = (f"from {sk_mod} import {C}\nfrom sklearn.compose import ColumnTransformer\n"
                        "from sklearn.pipeline import make_pipeline\n"
                        "from sklearn.preprocessing import OneHotEncoder, OrdinalEncoder, StandardScaler\n"
                        "from sklearn.impute import SimpleImputer\n")
        if a.model == "logreg":
            prep = ('ColumnTransformer([("num", make_pipeline(SimpleImputer(strategy="median"), StandardScaler()), '
                    '[c for c in X.columns if c not in CAT]), ("cat", OneHotEncoder(handle_unknown="ignore"), CAT)])')
            est = (f'{C}(C=params["C"], penalty=params["penalty"], solver="saga", max_iter=5000)' if classification
                   else f'{C}(alpha=1.0 / params["C"])')
        elif a.model == "hgb":
            prep = ('ColumnTransformer([("cat", OrdinalEncoder(handle_unknown="use_encoded_value", unknown_value=-1, '
                    'encoded_missing_value=-1), CAT)], remainder="passthrough")')
            est = f'{C}(**params, categorical_features=list(range(len(CAT))) or None, early_stopping=True, random_state=SEED)'
        else:
            prep = ('ColumnTransformer([("cat", OrdinalEncoder(handle_unknown="use_encoded_value", unknown_value=-1, '
                    'encoded_missing_value=-1), CAT)], remainder=SimpleImputer(strategy="median"))')
            est = f'{C}(**params, n_estimators=300, n_jobs=-1, random_state=SEED)'
        fit_block = (f"        model = make_pipeline({prep}, {est})\n"
                     "        model.fit(X_tr, y_tr)")
        refit = ("    trial = optuna.trial.FixedTrial(study.best_params)\n"
                 "    params = study.best_params\n"
                 f"    final = make_pipeline({prep}, {est}).fit(X, y)")
    space = SPACE[a.model].format(leaves_hi=leaves_hi, mcs_lo=max(2, mcs // 4), mcs_hi=mcs * 4)
    pruner = {"median": "optuna.pruners.MedianPruner(n_startup_trials=10, n_warmup_steps=1)",
              "hyperband": "optuna.pruners.HyperbandPruner(min_resource=1, max_resource=len(FOLDS))",
              "none": "optuna.pruners.NopPruner()"}[a.pruner]
    study_name = a.study_name or f"{a.model}_{a.target}"
    text = TEMPLATE.format(target=a.target, model=a.model, metric=a.metric, script=os.path.basename(a.output or "study.py"),
                           storage=f"sqlite:///{study_name}.db", study_name=study_name, extra_req=extra_req,
                           metric_fn=metric_fn, splitter_import=splitter, model_import=model_import, data=a.csv,
                           drop=drop, order_line=order_line, target_prep=target_prep, groups_line=groups_line,
                           cat_prep=cat_prep, cv_expr=cv_expr, score_body=score_body, space=space,
                           conditional=conditional, fit_block=fit_block, trials=a.trials, direction=direction,
                           pruner=pruner, patience=a.patience, refit_block=refit)
    if a.output:
        with open(a.output, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {a.output}: {a.model}, {a.metric} ({direction}), {splitter}, {a.trials} trials, "
              f"{a.pruner} pruner, storage sqlite:///{study_name}.db", file=sys.stderr)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
